//! Reflection-to-Zig backend. Zast is a host-tool dependency only.
//! `generate` borrows the schema for the call and returns allocator-owned source.
//! The generated module imports `flatzz`; retain buffer storage for borrowed views.
//! This backend is separate from the flatzz_compiler facade and is wired as the
//! host build's codegen module. It needs the sibling Zast checkout; generated
//! application modules depend only on flatzz.
//!
//! ## Complete host example
//!
//! Save as `codegen_example_test.zig` beside Flatzz's build file, with `../zast` present:
//!
//! ```zig
//! const std = @import("std");
//! const compiler = @import("flatzz_compiler");
//! const codegen = @import("codegen");
//!
//! test "generate a native schema module" {
//!     const allocator = std.testing.allocator;
//!     var arena = std.heap.ArenaAllocator.init(allocator);
//!     defer arena.deinit();
//!     const schema = try compiler.parser.parse(
//!         arena.allocator(),
//!         "table Reading { value:uint = 42; } root_type Reading;",
//!     );
//!     const source = try codegen.generate(allocator, schema);
//!     defer allocator.free(source);
//!     try std.testing.expect(std.mem.indexOf(u8, source, "pub const Reading") != null);
//! }
//! ```
//!
//! Run from the Flatzz root with Zig 0.17.0:
//!
//! ```sh
//! zig test --dep codegen --dep flatzz_compiler -Mroot=codegen_example_test.zig \
//!     --dep flatzz --dep flatzz_compiler --dep zast -Mcodegen=src/compiler/codegen.zig \
//!     --dep flatzz -Mflatzz_compiler=src/compiler.zig -Mflatzz=src/runtime.zig \
//!     -Mzast=../zast/src/root.zig
//! ```
//!
//! Expected result: a passing test with no application output. The owned source
//! exports Reading with value default 42. Compilation of generated source remains
//! a separate step; the host's `zig build check test` also exercises emitted modules.
const std = @import("std");
const flatzz = @import("flatzz");
const zast = @import("zast");
const compiler = @import("flatzz_compiler");
const Generator = @import("codegen/Generator.zig");

const reflection = compiler.reflection;
const Allocator = std.mem.Allocator;

/// Emit one module containing every declaration, including included schemas.
/// Strip the common namespace; quote remaining qualified names to avoid collisions.
/// Enum/union tags use snake_case, matching Flatzz's original Reading adapters.
/// Unsupported runtime features and malformed references fail before returning source.
/// The result owns its source bytes; free it with `allocator.free(source)`.
/// The schema is borrowed only for this call. Temporary descriptions, AST storage,
/// and unrendered source are released on success and failure; no partial output escapes.
/// Invalid indices, union pairs, or scalar defaults return `InvalidSchema`;
/// unsupported runtime features return `UnsupportedFeature`, and generated-name
/// collisions return `NameCollision`. Allocation errors propagate. This backend
/// does not perform every FBS semantic check or validate the emitted program.
/// Schema documentation is not emitted.
///
/// Inside a function with `std`, `compiler = @import("flatzz_compiler")`, and
/// this host backend imported as `codegen`:
/// ```zig
/// var arena = std.heap.ArenaAllocator.init(std.heap.page_allocator);
/// defer arena.deinit();
/// const schema = try compiler.parser.parse(
///     arena.allocator(),
///     "table Reading { value:uint = 42; } root_type Reading;",
/// );
/// const source = try codegen.generate(std.heap.page_allocator, schema);
/// defer std.heap.page_allocator.free(source);
/// ```
/// Expected result: owned Zig source exporting `Reading` with a `value` default
/// of 42 and importing only `flatzz`. Nothing is printed; compile the result with
/// that runtime import before using it in an application.
pub fn generate(allocator: Allocator, schema: reflection.Schema) ![]u8 {
    if (schema.advanced_features.default_vectors_and_strings or
        schema.advanced_features.unknown_bits != 0 or
        (schema.services != null and schema.services.?.len != 0)) return error.UnsupportedFeature;
    if (schema.file_ident) |identifier|
        if (identifier.len != flatzz.file_identifier_size) return error.InvalidSchema;
    var tree = generation_blk: {
        var arena = std.heap.ArenaAllocator.init(allocator);
        defer arena.deinit();
        var generator: Generator = .{
            .syntax = .{ .allocator = arena.allocator() },
            .schema = schema,
        };
        try generator.prepareNames();
        var context: zast.AstContext = .{};
        defer context.deinit(allocator);
        _ = try context.addNode(allocator, .root, 0, undefined);
        try context.source.appendSlice(
            allocator,
            "// Generated by flatzz --zig. Do not edit.\n" ++
                "// Wire IDs and layouts come from reflection metadata, never the native ABI.\n" ++
                "// Strings and views borrow their buffer; builders use caller-owned storage.\n",
        );
        try (zast.Declaration{ .value = try generator.syntax.builtin(
            "@import",
            &.{.{ .string_literal = "\"flatzz\"" }},
        ) })
            .emit(allocator, &context, "runtime", .private);
        try (zast.Declaration{ .value = try generator.syntax.builtin("@This", &.{}) }).emit(
            allocator,
            &context,
            "types",
            .private,
        );
        for (
            [_][]const u8{ "file_identifier", "file_extension" },
            [_]?[]const u8{ schema.file_ident, schema.file_ext },
        ) |name, metadata| {
            if (metadata) |value| try (zast.Declaration{ .value = .{
                .string_literal = try generator.syntax.allocator.print(
                    "\"{f}\"",
                    .{std.zig.fmtString(value)},
                ),
            } }).emit(allocator, &context, name, .public);
        }
        for (schema.enums, 0..) |enumeration, enum_index| {
            const description = try generator.enumeration(enumeration);
            try (zast.Declaration{ .value = description }).emit(
                allocator,
                &context,
                generator.enum_names[enum_index],
                .public,
            );
        }
        for (schema.objects, 0..) |object, object_index| {
            const description = try generator.object(object);
            try description.emit(
                allocator,
                &context,
                generator.object_names[object_index],
                .public,
            );
        }
        break :generation_blk try context.finish(allocator);
    };
    const source = tree.source;
    defer allocator.free(source);
    defer tree.deinit(allocator);
    return tree.renderAlloc(allocator);
}
