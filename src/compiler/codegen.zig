//! Reflection-to-Zig backend. Zast is a host-tool dependency only.
//! `generate` borrows the schema for the call and returns allocator-owned source.
//! The generated module imports `flatzz`; retain buffer storage for borrowed views.
const std = @import("std");
const flatzz = @import("flatzz");
const zast = @import("zast");
const reflection = @import("flatzz_compiler").reflection;
const BaseType = reflection.BaseType;
const Expression = zast.Expression;
const Member = zast.StructDeclaration.Member;
const Allocator = std.mem.Allocator;

/// Emit one module containing every declaration, including included schemas.
/// Strip the common namespace; quote remaining qualified names to avoid collisions.
/// Enum/union tags use snake_case, matching Flatzz's original Reading adapters.
/// Unsupported runtime features and malformed references fail before returning source.
/// The result owns its source bytes; free it with `allocator.free(source)`.
/// The schema is borrowed only for this call. Temporary descriptions, AST storage,
/// and unrendered source are released on success and failure; no partial output escapes.
/// Invalid indices, union pairs, or scalar defaults return `InvalidSchema`;
/// unsupported runtime features return `UnsupportedFeature`, and generated-name
/// collisions return `NameCollision`. Allocation errors propagate. This backend
/// does not perform every FBS semantic check or validate the emitted program.
/// Schema documentation is not emitted.
///
/// Inside a function with `std`, `compiler = @import("flatzz_compiler")`, and
/// this host backend imported as `codegen`:
/// ```zig
/// var arena = std.heap.ArenaAllocator.init(std.heap.page_allocator);
/// defer arena.deinit();
/// const schema = try compiler.parser.parse(arena.allocator(),
///     "table Reading { value:uint = 42; } root_type Reading;");
/// const source = try codegen.generate(std.heap.page_allocator, schema);
/// defer std.heap.page_allocator.free(source);
/// ```
/// Expected result: owned Zig source exporting `Reading` with a `value` default
/// of 42 and importing only `flatzz`. Nothing is printed; compile the result with
/// that runtime import before using it in an application.
pub fn generate(allocator: Allocator, schema: reflection.Schema) ![]u8 {
    if (schema.advanced_features.default_vectors_and_strings or schema.advanced_features.unknown_bits != 0 or
        (schema.services != null and schema.services.?.len != 0)) return error.UnsupportedFeature;
    if (schema.file_ident) |identifier| if (identifier.len != flatzz.file_identifier_size) return error.InvalidSchema;
    var arena = std.heap.ArenaAllocator.init(allocator);
    defer arena.deinit();
    var generator: Generator = .{ .allocator = arena.allocator(), .schema = schema };
    try generator.prepareNames();
    var context: zast.AstContext = .{};
    defer context.deinit(allocator);
    _ = try context.addNode(allocator, .root, 0, undefined);
    try context.source.appendSlice(allocator, "// Generated by flatzz-schema --zig. Do not edit.\n" ++
        "// Wire IDs and layouts come from reflection metadata, never the native ABI.\n" ++
        "// Strings and views borrow their buffer; builders use caller-owned storage.\n");
    try (zast.Declaration{ .value = try generator.builtin("@import", &.{.{ .string_literal = "\"flatzz\"" }}) })
        .emit(allocator, &context, "runtime", .private);
    try (zast.Declaration{ .value = try generator.builtin("@This", &.{}) }).emit(allocator, &context, "types", .private);
    inline for (.{ .{ "file_identifier", schema.file_ident }, .{ "file_extension", schema.file_ext } }) |entry| {
        if (entry[1]) |value| try (zast.Declaration{ .value = .{
            .string_literal = try std.fmt.allocPrint(generator.allocator, "\"{f}\"", .{std.zig.fmtString(value)}),
        } }).emit(allocator, &context, entry[0], .public);
    }
    for (schema.enums, 0..) |enumeration, enum_index| {
        const description = try generator.enumeration(enumeration);
        try (zast.Declaration{ .value = description }).emit(allocator, &context, generator.enum_names[enum_index], .public);
    }
    for (schema.objects, 0..) |object, object_index| {
        const description = try generator.object(object);
        try description.emit(allocator, &context, generator.object_names[object_index], .public);
    }
    var tree = try context.finish(allocator);
    const source = tree.source;
    defer allocator.free(source);
    defer tree.deinit(allocator);
    return tree.renderAlloc(allocator);
}

// Dynamic descriptions and escaped names share the scratch arena through rendering.
const Generator = struct {
    allocator: Allocator,
    schema: reflection.Schema,
    object_names: []const []const u8 = &.{},
    enum_names: []const []const u8 = &.{},

    fn store(self: *Generator, value: anytype) !*@TypeOf(value) {
        const result = try self.allocator.create(@TypeOf(value));
        result.* = value;
        return result;
    }

    fn identifierExpression(name: []const u8) Expression {
        return .{ .identifier = name };
    }

    fn identifier(self: *Generator, name: []const u8) ![]const u8 {
        if (name.len == 0) return error.InvalidSchema;
        return std.fmt.allocPrint(self.allocator, "{f}", .{std.zig.fmtId(name)});
    }

    fn access(self: *Generator, base: Expression, name: []const u8) !Expression {
        return .{ .field_access = .{ .base = try self.store(base), .name = name } };
    }

    fn call(self: *Generator, callee: Expression, arguments: []const Expression) !Expression {
        return .{ .call = .{ .callee = try self.store(callee), .arguments = try self.allocator.dupe(Expression, arguments) } };
    }

    fn builtin(self: *Generator, name: []const u8, arguments: []const Expression) !Expression {
        return .{ .builtin_call = .{ .name = name, .arguments = try self.allocator.dupe(Expression, arguments) } };
    }

    fn runtimeCall(self: *Generator, name: []const u8, arguments: []const Expression) !Expression {
        return self.call(try self.access(identifierExpression("runtime"), name), arguments);
    }

    fn record(self: *Generator, fields: []const Expression.InitializerField) !Expression {
        return .{ .struct_init = .{ .fields = try self.allocator.dupe(Expression.InitializerField, fields), .trailing_comma = true } };
    }

    fn kind(self: *Generator, name: []const u8, value: Expression) !Expression {
        return self.record(&.{.{ .name = name, .value = value }});
    }

    fn optional(self: *Generator, child: Expression) !Expression {
        return .{ .optional_type = try self.store(child) };
    }

    fn slice(self: *Generator, child: Expression) !Expression {
        return .{ .slice_type = .{ .child_type = try self.store(child), .is_const = true } };
    }

    fn number(self: *Generator, value: anytype) !Expression {
        return .{ .integer_literal = try std.fmt.allocPrint(self.allocator, "{d}", .{value}) };
    }

    fn binding(name: []const u8, value: Expression) Member {
        return .{ .declaration = .{ .name = name, .declaration = .{ .value = value }, .visibility = .public } };
    }

    fn function(self: *Generator, name: []const u8, parameters: []const zast.FunctionDeclaration.Parameter, result: Expression, statements: []const zast.Block.Statement) !Member {
        return .{ .function = .{
            .name = name,
            .visibility = .public,
            .declaration = try self.store(zast.FunctionDeclaration{
                .parameters = try self.allocator.dupe(zast.FunctionDeclaration.Parameter, parameters),
                .return_type = result,
                .body = .{ .statements = try self.allocator.dupe(zast.Block.Statement, statements) },
            }),
        } };
    }

    fn prepareNames(self: *Generator) !void {
        var common: ?[]const u8 = null;
        for (self.schema.objects) |object_value| common = commonNamespace(common, object_value.name);
        for (self.schema.enums) |enum_value| common = commonNamespace(common, enum_value.name);
        const prefix = common orelse "";
        var names: std.StringHashMapUnmanaged(void) = .empty;
        for ([_][]const u8{ "runtime", "types", "file_identifier", "file_extension" }) |name| try names.put(self.allocator, name, {});
        const objects = try self.allocator.alloc([]const u8, self.schema.objects.len);
        const enums = try self.allocator.alloc([]const u8, self.schema.enums.len);
        inline for (.{ .{ self.schema.objects, objects }, .{ self.schema.enums, enums } }) |group| {
            for (group[0], group[1]) |declaration, *name| {
                const raw_name = declaration.name[if (prefix.len == 0) 0 else prefix.len + 1..];
                if ((try names.getOrPut(self.allocator, raw_name)).found_existing) return error.NameCollision;
                name.* = try self.identifier(raw_name);
            }
        }
        self.object_names = objects;
        self.enum_names = enums;
    }

    fn objectIndex(self: *Generator, index: i32) !usize {
        const result = std.math.cast(usize, index) orelse return error.InvalidSchema;
        if (result >= self.schema.objects.len) return error.InvalidSchema;
        return result;
    }

    fn enumIndex(self: *Generator, index: i32, is_union: bool) !usize {
        const result = std.math.cast(usize, index) orelse return error.InvalidSchema;
        if (result >= self.schema.enums.len or self.schema.enums[result].is_union != is_union) return error.InvalidSchema;
        return result;
    }

    fn named(self: *Generator, name: []const u8) !Expression {
        return self.access(identifierExpression("types"), name);
    }

    fn layout(self: *Generator, index: i32) !Expression {
        const object_index = try self.objectIndex(index);
        if (!self.schema.objects[object_index].is_struct) return error.InvalidSchema;
        return self.access(try self.named(self.object_names[object_index]), "Layout");
    }

    fn scalarType(self: *Generator, field_type: reflection.Type) !Expression {
        const primitive = scalarName(field_type.base_type) orelse return error.UnsupportedFeature;
        if (field_type.index == -1) return identifierExpression(primitive);
        const index = try self.enumIndex(field_type.index, false);
        if (self.schema.enums[index].underlying_type.base_type != field_type.base_type) return error.InvalidSchema;
        return self.named(self.enum_names[index]);
    }

    fn integer(self: *Generator, value: i64, base: BaseType) !Expression {
        const name = scalarName(base) orelse return error.UnsupportedFeature;
        if (name[0] != 'i' and name[0] != 'u') return error.InvalidSchema;
        const bits = try std.fmt.parseInt(u7, name[1..], 10);
        const unsigned = name[0] == 'u';
        const integer_value: i128 = if (base == .ULong) @as(u64, @bitCast(value)) else value;
        const bound = @as(i128, 1) << @intCast(bits - @intFromBool(!unsigned));
        if (integer_value < (if (unsigned) @as(i128, 0) else -bound) or integer_value >= bound) return error.InvalidSchema;
        return if (integer_value < 0) .{ .negate = try self.store(try self.number(-integer_value)) } else self.number(integer_value);
    }

    fn defaultValue(self: *Generator, field: reflection.Field) !Expression {
        if (field.optional) return identifierExpression("null");
        const field_type = field.type.*;
        if (field_type.index >= 0) {
            _ = try self.enumIndex(field_type.index, false);
            return self.builtin("@fromBackingInt", &.{try self.integer(field.default_integer, field_type.base_type)});
        }
        return switch (field_type.base_type) {
            .Bool => if (field.default_integer == 0 or field.default_integer == 1)
                identifierExpression(if (field.default_integer == 1) "true" else "false")
            else
                error.InvalidSchema,
            .Float, .Double => float_default_blk: {
                const bits: u64 = if (field_type.base_type == .Float)
                    @as(u32, @bitCast(@as(f32, @floatCast(field.default_real))))
                else
                    @bitCast(field.default_real);
                if (bits == 0) break :float_default_blk try self.number(@as(u8, 0));
                // Bit patterns preserve negative zero, infinities and NaNs without
                // requiring a float-literal extension to Zast's expression API.
                break :float_default_blk try self.builtin("@bitCast", &.{try self.builtin("@as", &.{
                    identifierExpression(if (field_type.base_type == .Float) "u32" else "u64"), try self.number(bits),
                })});
            },
            else => self.integer(field.default_integer, field_type.base_type),
        };
    }

    fn enumeration(self: *Generator, value: reflection.Enum) !Expression {
        const backing = if (value.is_union) "u8" else scalarName(value.underlying_type.base_type) orelse return error.UnsupportedFeature;
        if (value.is_union and value.underlying_type.base_type != .UType and value.underlying_type.base_type != .UByte) return error.UnsupportedFeature;
        if (backing[0] != 'i' and backing[0] != 'u') return error.UnsupportedFeature;
        const width = try std.fmt.parseInt(u7, backing[1..], 10);
        const fields = try self.allocator.alloc(zast.Field, value.values.len);
        const variants = try self.allocator.alloc(Expression.InitializerField, if (value.is_union) value.values.len else 0);
        var names: std.StringHashMapUnmanaged(void) = .empty;
        var numbers: std.AutoHashMapUnmanaged(i64, void) = .empty;
        var has_none = false;
        for (value.values, fields, 0..) |item, *field, index| {
            const tag = try snake(self.allocator, item.name);
            if (std.mem.eql(u8, tag, "_") or (try names.getOrPut(self.allocator, tag)).found_existing) return error.NameCollision;
            if ((try numbers.getOrPut(self.allocator, item.value)).found_existing) return error.UnsupportedFeature;
            const name = try self.identifier(tag);
            field.* = .{ .name = name, .value = try self.integer(item.value, if (value.is_union) .UByte else value.underlying_type.base_type) };
            if (value.is_union) {
                const payload = item.union_type orelse return error.InvalidSchema;
                const kind_value: Expression = switch (payload.base_type) {
                    .None => none_variant_blk: {
                        if (item.value != 0 or !std.mem.eql(u8, tag, "none")) return error.InvalidSchema;
                        has_none = true;
                        break :none_variant_blk .{ .enum_literal = "none" };
                    },
                    .String => .{ .enum_literal = "string" },
                    .Obj => union_payload_blk: {
                        const object_index = try self.objectIndex(payload.index);
                        break :union_payload_blk if (self.schema.objects[object_index].is_struct)
                            try self.kind("structure", try self.layout(payload.index))
                        else
                            try self.kind("table", try self.named(self.object_names[object_index]));
                    },
                    else => return error.UnsupportedFeature,
                };
                variants[index] = .{ .name = name, .value = kind_value };
            }
        }
        const description = try self.store(zast.EnumDeclaration{
            .backing_type = backing,
            .fields = fields,
            .non_exhaustive = !value.is_union and @as(u128, value.values.len) < (@as(u128, 1) << width),
        });
        if (!value.is_union) return Expression.fromType(description);
        if (!has_none) return error.InvalidSchema;
        return self.runtimeCall("Union", &.{ Expression.fromType(description), try self.record(variants) });
    }

    fn nativeType(self: *Generator, field_type: reflection.Type) anyerror!Expression {
        return switch (field_type.base_type) {
            .String => self.slice(identifierExpression("u8")),
            .Obj => native_object_blk: {
                const object_index = try self.objectIndex(field_type.index);
                const child = try self.named(self.object_names[object_index]);
                break :native_object_blk if (self.schema.objects[object_index].is_struct) child else .{ .pointer_type = .{ .child_type = try self.store(child), .is_const = true } };
            },
            .Union => self.access(try self.named(self.enum_names[try self.enumIndex(field_type.index, true)]), "Value"),
            .Vector, .Array => native_sequence_blk: {
                if (scalarName(field_type.element) == null and field_type.element != .Obj and
                    !(field_type.base_type == .Vector and (field_type.element == .String or field_type.element == .Union))) return error.UnsupportedFeature;
                if (field_type.base_type == .Array and field_type.fixed_length == 0) return error.InvalidSchema;
                var element = field_type;
                element.base_type = field_type.element;
                const child = try self.nativeType(element);
                break :native_sequence_blk if (field_type.base_type == .Vector) try self.slice(child) else .{ .array_type = .{
                    .child_type = try self.store(child),
                    .length = try self.store(try self.number(field_type.fixed_length)),
                } };
            },
            else => self.scalarType(field_type),
        };
    }

    fn descriptor(self: *Generator, field: reflection.Field, structure: bool) !Expression {
        const field_type = field.type.*;
        const position = try self.number(if (structure) field.offset else field.id);
        if (structure) return switch (field_type.base_type) {
            .Obj => self.runtimeCall("StructMember", &.{ try self.layout(field_type.index), position }),
            .Array => self.runtimeCall("ArrayMember", &.{
                try self.kind(if (field_type.element == .Obj) "structure" else "scalar", if (field_type.element == .Obj) try self.layout(field_type.index) else try self.scalarType(.{ .base_type = field_type.element, .index = field_type.index })),
                try self.number(field_type.fixed_length),
                position,
            }),
            else => self.runtimeCall("ScalarMember", &.{ try self.scalarType(field_type), position }),
        };
        const options = try self.record(if (field.required) &.{.{ .name = "required", .value = identifierExpression("true") }} else &.{});
        return switch (field_type.base_type) {
            .Union => self.runtimeCall("UnionField", &.{
                try self.named(self.enum_names[try self.enumIndex(field_type.index, true)]), try self.unionIds(field), options,
            }),
            .Vector => if (field_type.element == .Union) self.runtimeCall("UnionVectorField", &.{
                try self.named(self.enum_names[try self.enumIndex(field_type.index, true)]), try self.unionIds(field), options,
            }) else self.runtimeCall("ReferenceField", &.{ position, try self.kind("vector", try self.codec(field_type)), options }),
            .String => self.runtimeCall("ReferenceField", &.{ position, .{ .enum_literal = "string" }, options }),
            .Obj => object_descriptor_blk: {
                const object_index = try self.objectIndex(field_type.index);
                break :object_descriptor_blk if (self.schema.objects[object_index].is_struct)
                    self.runtimeCall("StructField", &.{ try self.layout(field_type.index), position, options })
                else
                    self.runtimeCall("ReferenceField", &.{ position, try self.kind("table", try self.named(self.object_names[object_index])), options });
            },
            else => self.runtimeCall("ScalarField", &.{
                if (field.optional) try self.optional(try self.scalarType(field_type)) else try self.scalarType(field_type),
                position,
                try self.defaultValue(field),
            }),
        };
    }

    fn unionIds(self: *Generator, field: reflection.Field) !Expression {
        if (field.id == 0) return error.InvalidSchema;
        return self.record(&.{
            .{ .name = "tag", .value = try self.number(field.id - 1) },
            .{ .name = "value", .value = try self.number(field.id) },
        });
    }

    fn codec(self: *Generator, field_type: reflection.Type) !Expression {
        return switch (field_type.element) {
            .String => self.access(identifierExpression("runtime"), "StringCodec"),
            .Obj => object_codec_blk: {
                const object_index = try self.objectIndex(field_type.index);
                break :object_codec_blk if (self.schema.objects[object_index].is_struct)
                    self.runtimeCall("StructCodec", &.{try self.layout(field_type.index)})
                else
                    self.runtimeCall("TableCodec", &.{try self.named(self.object_names[object_index])});
            },
            else => self.runtimeCall("ScalarCodec", &.{try self.scalarType(.{ .base_type = field_type.element, .index = field_type.index })}),
        };
    }

    fn object(self: *Generator, value: reflection.Object) !zast.StructDeclaration {
        const ordered = try self.allocator.dupe(reflection.Field, value.fields);
        std.mem.sort(reflection.Field, ordered, {}, struct {
            fn less(_: void, left: reflection.Field, right: reflection.Field) bool {
                return left.id < right.id;
            }
        }.less);
        var members: std.ArrayList(Member) = .empty;
        var descriptors: std.ArrayList(Expression.InitializerField) = .empty;
        var capacities: std.ArrayList(zast.FunctionDeclaration.Parameter) = .empty;
        var budgets: std.ArrayList(Expression.InitializerField) = .empty;
        var member_names: std.StringHashMapUnmanaged(void) = .empty;
        for (ordered, 0..) |field, field_index| {
            if (field_index != 0 and ordered[field_index - 1].id == field.id) return error.InvalidSchema;
            if (field.offset64 or field.type.base_type == .Vector64) return error.UnsupportedFeature;
            const field_type = field.type;
            if (isTag(field)) {
                if (value.is_struct or field_index + 1 >= ordered.len) return error.InvalidSchema;
                const payload = ordered[field_index + 1];
                if (!isUnion(payload) or payload.id == 0 or payload.id - 1 != field.id or
                    payload.type.index != field_type.index or payload.deprecated != field.deprecated or
                    (payload.type.base_type == .Vector) != (field_type.base_type == .Vector)) return error.InvalidSchema;
                continue;
            }
            if (isUnion(field) and (field_index == 0 or !isTag(ordered[field_index - 1]))) return error.InvalidSchema;
            if (field.deprecated) continue;
            for ([_][]const u8{ "runtime", "types", "fields", "Schema", "Layout", "Field", "View", "WriteOptions", "Storage", "write", "read", "update", "verify" }) |reserved| {
                if (std.mem.eql(u8, field.name, reserved)) return error.NameCollision;
            }
            if ((try member_names.getOrPut(self.allocator, field.name)).found_existing) return error.NameCollision;
            const name = try self.identifier(field.name);
            const fixed = scalarName(field_type.base_type) != null;
            var native = try self.nativeType(field_type.*);
            if (!value.is_struct and field_type.base_type != .Union and (!fixed or field.optional)) native = try self.optional(native);
            try members.append(self.allocator, .{ .field = .{
                .name = name,
                .type_expression = native,
                .value = if (value.is_struct) null else if (fixed)
                    try self.access(try self.access(identifierExpression("fields"), name), "default")
                else if (field_type.base_type == .Union) .{ .enum_literal = "none" } else identifierExpression("null"),
            } });
            try descriptors.append(self.allocator, .{ .name = name, .value = try self.descriptor(field, value.is_struct) });
            if (!value.is_struct and !fixed and !(field_type.base_type == .Obj and self.schema.objects[try self.objectIndex(field_type.index)].is_struct)) {
                const parameter_name = try self.identifier(try std.fmt.allocPrint(self.allocator, "{s}_capacity", .{field.name}));
                const record_budget = field_type.base_type == .Vector and (field_type.element == .String or field_type.element == .Union or
                    (field_type.element == .Obj and !self.schema.objects[try self.objectIndex(field_type.index)].is_struct));
                const budget_type: Expression = if (record_budget) Expression.fromType(try self.store(zast.StructDeclaration{ .members = try self.allocator.dupe(Member, &.{
                    .{ .field = .{ .name = "count", .type_expression = identifierExpression("usize"), .value = try self.number(@as(u8, 0)) } },
                    .{ .field = .{ .name = "bytes", .type_expression = identifierExpression("usize"), .value = try self.number(@as(u8, 0)) } },
                }) })) else identifierExpression("usize");
                try capacities.append(self.allocator, .{ .name = parameter_name, .type_expression = budget_type, .is_comptime = true });
                try budgets.append(self.allocator, .{ .name = name, .value = identifierExpression(parameter_name) });
            }
        }
        if (value.is_struct) {
            if (value.bytesize <= 0 or value.minalign <= 0) return error.InvalidSchema;
            try members.append(self.allocator, binding("Layout", try self.runtimeCall("StructLayout", &.{
                try self.builtin("@This", &.{}),
                try self.record(&.{
                    .{ .name = "size", .value = try self.number(value.bytesize) },
                    .{ .name = "alignment", .value = try self.number(value.minalign) },
                }),
                try self.record(descriptors.items),
            })));
        } else {
            try members.append(self.allocator, binding("fields", try self.record(descriptors.items)));
            try members.append(self.allocator, binding("Schema", try self.runtimeCall("Schema", &.{ try self.builtin("@This", &.{}), identifierExpression("fields") })));
            inline for (.{ .{ "Field", "Field" }, .{ "View", "View" }, .{ "write", "writeRoot" }, .{ "read", "readRoot" }, .{ "update", "updateRoot" }, .{ "verify", "verifyRoot" } }) |alias| {
                try members.append(self.allocator, binding(alias[0], try self.access(identifierExpression("Schema"), alias[1])));
            }
            try members.append(self.allocator, binding("WriteOptions", try self.access(identifierExpression("runtime"), "WriteOptions")));
            try members.append(self.allocator, try self.function("Storage", capacities.items, identifierExpression("type"), &.{.{ .return_value = try self.runtimeCall("Storage", &.{
                identifierExpression("Schema"), try self.record(budgets.items), try self.record(&.{}),
            }) }}));
            for (ordered) |field| {
                if (field.deprecated or isTag(field) or scalarName(field.type.base_type) != null or field.type.base_type == .String) continue;
                const name = try self.identifier(field.name);
                const mutable_raw = try self.mutableName(field.name);
                if ((try member_names.getOrPut(self.allocator, mutable_raw)).found_existing) return error.NameCollision;
                const mutable_name = try self.identifier(mutable_raw);
                try members.append(self.allocator, try self.function(mutable_name, &.{.{ .name = "bytes", .type_expression = .{ .slice_type = .{ .child_type = try self.store(identifierExpression("u8")) } } }}, .{ .error_union_type = .{
                    .error_set = try self.store(try self.access(identifierExpression("runtime"), "AccessError")),
                    .payload_type = try self.store(try self.call(try self.access(identifierExpression("Schema"), "MutableView"), &.{.{ .enum_literal = name }})),
                } }, &.{
                    .{ .declaration = .{ .name = "table", .declaration = .{ .value = .{ .@"try" = try self.store(try self.call(
                        try self.access(try self.access(identifierExpression("runtime"), "MutableTable"), "from"),
                        &.{ identifierExpression("bytes"), .{ .enum_literal = "root" } },
                    )) } } } },
                    .{ .return_value = try self.call(try self.access(identifierExpression("Schema"), "borrowMutable"), &.{ identifierExpression("table"), .{ .enum_literal = name } }) },
                }));
            }
        }
        return .{ .members = members.items };
    }

    fn mutableName(self: *Generator, name: []const u8) ![]const u8 {
        var result: std.ArrayList(u8) = .empty;
        try result.appendSlice(self.allocator, "mutable");
        var upper = true;
        for (name) |byte| {
            if (byte == '_') {
                upper = true;
                continue;
            }
            try result.append(self.allocator, if (upper) std.ascii.toUpper(byte) else byte);
            upper = false;
        }
        return result.items;
    }
};

fn commonNamespace(existing: ?[]const u8, name: []const u8) []const u8 {
    const namespace = name[0 .. std.mem.lastIndexOfScalar(u8, name, '.') orelse 0];
    var result = existing orelse return namespace;
    while (result.len != 0 and !(std.mem.eql(u8, result, namespace) or
        (std.mem.startsWith(u8, namespace, result) and namespace.len > result.len and namespace[result.len] == '.')))
        result = result[0 .. std.mem.lastIndexOfScalar(u8, result, '.') orelse 0];
    return result;
}

fn snake(allocator: Allocator, name: []const u8) ![]const u8 {
    var result: std.ArrayList(u8) = .empty;
    for (name, 0..) |byte, index| {
        if (std.ascii.isUpper(byte) and index > 0 and name[index - 1] != '_' and
            (std.ascii.isLower(name[index - 1]) or std.ascii.isDigit(name[index - 1]) or
                (index + 1 < name.len and std.ascii.isLower(name[index + 1])))) try result.append(allocator, '_');
        try result.append(allocator, std.ascii.toLower(byte));
    }
    return result.items;
}

fn isTag(field: reflection.Field) bool {
    return field.type.base_type == .UType or (field.type.base_type == .Vector and field.type.element == .UType);
}

fn isUnion(field: reflection.Field) bool {
    return field.type.base_type == .Union or (field.type.base_type == .Vector and field.type.element == .Union);
}

fn scalarName(base: BaseType) ?[]const u8 {
    return switch (base) {
        .Bool => "bool",
        .Byte => "i8",
        .UByte => "u8",
        .Short => "i16",
        .UShort => "u16",
        .Int => "i32",
        .UInt => "u32",
        .Long => "i64",
        .ULong => "u64",
        .Float => "f32",
        .Double => "f64",
        else => null,
    };
}
